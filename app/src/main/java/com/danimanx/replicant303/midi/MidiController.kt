/**
 * USB MIDI 1.0 + MIDI 2.0 UMP transport manager.
 *
 * Android's MidiManager owns the USB permission flow; we only enumerate
 * devices, open ports, and translate packets. MIDI clock and transport are
 * generated by the native engine, so outgoing events carry the engine's audio
 * timestamp and are scheduled by [MidiInputPort.send].
 */
class MidiController(
    private val context: Context,
    private val engine: EngineController
) {
    private val prefs = context.getSharedPreferences("midi", Context.MODE_PRIVATE)
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private val handler = Handler(Looper.getMainLooper())
    private val midiManager = context.getSystemService(Context.MIDI_SERVICE) as? MidiManager
    private val usbManager = context.getSystemService(Context.USB_SERVICE) as? UsbManager

    private val _state = MutableStateFlow(
        MidiUiState(
            available = midiManager != null,
            umpSupported = Build.VERSION.SDK_INT >= 33,
            midiInEnabled = prefs.getBoolean(KEY_IN_ENABLED, true),
            midiOutEnabled = prefs.getBoolean(KEY_OUT_ENABLED, true),
            clockSend = prefs.getBoolean(KEY_CLOCK_SEND, true),
            clockReceive = prefs.getBoolean(KEY_CLOCK_RECEIVE, false),
            transportSend = prefs.getBoolean(KEY_TRANSPORT_SEND, true),
            channelFilter = prefs.getInt(KEY_CHANNEL, -1),
            useUmp = prefs.getBoolean(KEY_USE_UMP, false)
        )
    )
    val state: StateFlow<MidiUiState> = _state

    private var inputInfo: MidiDeviceInfo? = null
    private var inputDevice: MidiDevice? = null
    private var inputPort: MidiOutputPort? = null
    private var inputReceiver: MidiReceiver? = null
    private var inputUsesUmp = false

    private var outputInfo: MidiDeviceInfo? = null
    private var outputDevice: MidiDevice? = null
    private var outputPort: MidiInputPort? = null
    private var outputUsesUmp = false

    private val parser = MidiStreamParser()
    private val logId = AtomicLong(0)
    private val lastClockLogMs = AtomicLong(0L)
    private var started = false
    private var autoConnectDone = false
    private var reconnectNeeded = false
    private var outputPump: Job? = null

    private val deviceCallback = object : MidiManager.DeviceCallback() {
        override fun onDeviceAdded(device: MidiDeviceInfo) {
            // A replug is a fresh enumeration: pick the saved device back up.
            refreshDevices(autoConnect = true)
        }

        override fun onDeviceRemoved(device: MidiDeviceInfo) {
            if (device.id == inputInfo?.id) disconnectInput()
            if (device.id == outputInfo?.id) disconnectOutput()
            refreshDevices()
        }
    }

    private val usbPermissionReceiver = object : BroadcastReceiver() {
        override fun onReceive(ctx: Context?, intent: Intent?) {
            if (intent?.action == ACTION_USB_PERMISSION) refreshDevices()
        }
    }

    fun start() {
        if (started) return
        started = true
        val manager = midiManager ?: run {
            _state.update { it.copy(available = false, error = "This device does not expose the Android MIDI service.") }
            return
        }

        engine.setMidiOutEnabled(_state.value.midiOutEnabled)
        engine.setClockSend(_state.value.clockSend)
        engine.setClockReceive(_state.value.clockReceive)
        engine.setTransportSend(_state.value.transportSend)
        engine.setMidiChannel(_state.value.channelFilter)

        runCatching {
            manager.registerDeviceCallback(deviceCallback, handler)
        }.onFailure {
            _state.update { s -> s.copy(error = "Could not register the MIDI device callback.") }
        }

        runCatching {
            ContextCompat.registerReceiver(
                context,
                usbPermissionReceiver,
                IntentFilter(ACTION_USB_PERMISSION),
                ContextCompat.RECEIVER_NOT_EXPORTED
            )
        }

        refreshDevices(autoConnect = true)
        scope.launch {
            delay(900)
            refreshDevices(autoConnect = !autoConnectDone)
        }
        startOutputPump()
    }

    fun disconnectAll() {
        disconnectInput()
        disconnectOutput()
        reconnectNeeded = true
    }

    fun reconnectSaved() {
        if (!reconnectNeeded && (inputPort != null || outputPort != null)) return
        reconnectNeeded = false
        if (_state.value.devices.isEmpty()) {
            refreshDevices(autoConnect = true)
        } else {
            autoConnectSavedDevices()
        }
    }

    /**
     * Reconnects the last used input/output by stable id, falling back to the
     * remembered device name because Android USB MIDI ids change per plug.
     */
    private fun autoConnectSavedDevices() {
        val devices = _state.value.devices
        if (devices.isEmpty()) return

        if (inputPort == null) {
            val savedId = prefs.getInt(KEY_INPUT_ID, -1)
            val savedName = prefs.getString(KEY_INPUT_NAME, null)
            val match = devices.firstOrNull { it.id == savedId && it.inputPorts > 0 }
                ?: savedName?.let { name ->
                    devices.firstOrNull { it.name == name && it.inputPorts > 0 }
                }
            if (match != null) connectInput(match.id)
        }

        if (outputPort == null) {
            val savedId = prefs.getInt(KEY_OUTPUT_ID, -1)
            val savedName = prefs.getString(KEY_OUTPUT_NAME, null)
            val match = devices.firstOrNull { it.id == savedId && it.outputPorts > 0 }
                ?: savedName?.let { name ->
                    devices.firstOrNull { it.name == name && it.outputPorts > 0 }
                }
            if (match != null) connectOutput(match.id)
        }
    }

    fun release() {
        outputPump?.cancel()
        outputPump = null
        disconnectInput()
        disconnectOutput()
        runCatching { midiManager?.unregisterDeviceCallback(deviceCallback) }
        runCatching { context.unregisterReceiver(usbPermissionReceiver) }
        scope.cancel()
        started = false
    }

    fun refreshDevices(autoConnect: Boolean = false) {
        val manager = midiManager ?: return
        val infos = LinkedHashMap<Int, MidiDeviceInfo>()
        runCatching {
            if (Build.VERSION.SDK_INT >= 33) {
                manager.getDevicesForTransport(MidiManager.TRANSPORT_MIDI_BYTE_STREAM)
                    .forEach { infos[it.id] = it }
            } else {
                manager.devices?.forEach { infos[it.id] = it }
            }
        }
        val umpIds = if (Build.VERSION.SDK_INT >= 33) {
            runCatching {
                manager.getDevicesForTransport(MidiManager.TRANSPORT_UNIVERSAL_MIDI_PACKETS)
                    .map { it.id }
                    .toSet()
            }.getOrElse { emptySet() }
        } else {
            emptySet()
        }
        if (Build.VERSION.SDK_INT >= 33) {
            runCatching {
                manager.getDevicesForTransport(MidiManager.TRANSPORT_UNIVERSAL_MIDI_PACKETS)
                    .forEach { infos[it.id] = it }
            }
        }

        val entries = infos.values.map { info ->
            val ports = info.ports
            val toApp = ports.count { it.type == MidiDeviceInfo.PortInfo.TYPE_OUTPUT }
            val fromApp = ports.count { it.type == MidiDeviceInfo.PortInfo.TYPE_INPUT }
            val props = info.properties
            val name = props.getString(MidiDeviceInfo.PROPERTY_NAME)
                ?: props.getString(MidiDeviceInfo.PROPERTY_PRODUCT)
                ?: props.getString(MidiDeviceInfo.PROPERTY_MANUFACTURER)
                ?: "MIDI device ${info.id}"
            MidiDeviceEntry(
                id = info.id,
                name = name,
                manufacturer = props.getString(MidiDeviceInfo.PROPERTY_MANUFACTURER) ?: "",
                typeLabel = when (info.type) {
                    MidiDeviceInfo.TYPE_USB -> "USB"
                    MidiDeviceInfo.TYPE_BLUETOOTH -> "BLE"
                    MidiDeviceInfo.TYPE_VIRTUAL -> "VIRTUAL"
                    else -> "MIDI"
                },
                inputPorts = toApp,
                outputPorts = fromApp,
                isUmp = umpIds.contains(info.id),
                isInputConnected = info.id == inputInfo?.id && inputPort != null,
                isOutputConnected = info.id == outputInfo?.id && outputPort != null
            )
        }.sortedBy { it.name.lowercase() }

        _state.update { it.copy(devices = entries, scanning = false) }

        if (autoConnect && infos.isNotEmpty()) {
            autoConnectDone = true
            autoConnectSavedDevices()
        }
    }

    private suspend fun openDevice(info: MidiDeviceInfo): MidiDevice? {
        val manager = midiManager ?: return null
        return withTimeoutOrNull(5000) {
            suspendCancellableCoroutine { continuation ->
                var resumed = false
                manager.openDevice(info, { device ->
                    if (!resumed) {
                        resumed = true
                        if (continuation.isActive) continuation.resume(device)
                    }
                }, handler)
            }
        }
    }

    fun connectInput(deviceId: Int) {
        val manager = midiManager ?: return
        val info = findDeviceInfo(deviceId) ?: run {
            _state.update { it.copy(error = "That MIDI input is no longer connected.") }
            return
        }
        disconnectInput()
        scope.launch {
            val device = openDevice(info)
            if (device == null) {
                requestUsbPermission(info)
                _state.update {
                    it.copy(error = "Android did not grant access. Approve the USB prompt, then tap Connect again.")
                }
                return@launch
            }
            val portInfo = info.ports.firstOrNull { it.type == MidiDeviceInfo.PortInfo.TYPE_OUTPUT }
            if (portInfo == null) {
                runCatching { device.close() }
                _state.update { it.copy(error = "This device has no MIDI output port to listen to.") }
                return@launch
            }
            val port = runCatching { device.openOutputPort(portInfo.portNumber) }.getOrNull()
            if (port == null) {
                runCatching { device.close() }
                _state.update { it.copy(error = "Could not open the MIDI input port.") }
                return@launch
            }

            val receiver = object : MidiReceiver() {
                override fun onSend(msg: ByteArray?, offset: Int, count: Int, timestamp: Long) {
                    if (msg == null) return
                    handleIncoming(msg, offset, count, timestamp)
                }
            }
            val connected = runCatching { port.connect(receiver) }.isSuccess
            if (!connected) {
                runCatching { port.close() }
                runCatching { device.close() }
                _state.update { it.copy(error = "Android rejected the MIDI input connection.") }
                return@launch
            }

            inputInfo = info
            inputDevice = device
            inputPort = port
            inputReceiver = receiver
            inputUsesUmp = _state.value.useUmp && isUmpDevice(info)
            parser.reset()
            prefs.edit()
                .putInt(KEY_INPUT_ID, info.id)
                .putString(KEY_INPUT_NAME, deviceName(info))
                .apply()
            _state.update {
                it.copy(
                    inputDeviceId = info.id,
                    inputDeviceName = deviceName(info),
                    inputConnected = true,
                    error = null
                )
            }
            refreshDevices()
        }
    }

    fun connectOutput(deviceId: Int) {
        val manager = midiManager ?: return
        val info = findDeviceInfo(deviceId) ?: run {
            _state.update { it.copy(error = "That MIDI output is no longer connected.") }
            return
        }
        disconnectOutput()
        scope.launch {
            val device = openDevice(info)
            if (device == null) {
                requestUsbPermission(info)
                _state.update {
                    it.copy(error = "Android did not grant access. Approve the USB prompt, then tap Connect again.")
                }
                return@launch
            }
            val portInfo = info.ports.firstOrNull { it.type == MidiDeviceInfo.PortInfo.TYPE_INPUT }
            if (portInfo == null) {
                runCatching { device.close() }
                _state.update { it.copy(error = "This device has no MIDI input port to send to.") }
                return@launch
            }
            val port = runCatching { device.openInputPort(portInfo.portNumber) }.getOrNull()
            if (port == null) {
                runCatching { device.close() }
                _state.update { it.copy(error = "Could not open the MIDI output port.") }
                return@launch
            }

            outputInfo = info
            outputDevice = device
            outputPort = port
            outputUsesUmp = _state.value.useUmp && isUmpDevice(info)
            prefs.edit()
                .putInt(KEY_OUTPUT_ID, info.id)
                .putString(KEY_OUTPUT_NAME, deviceName(info))
                .apply()
            _state.update {
                it.copy(
                    outputDeviceId = info.id,
                    outputDeviceName = deviceName(info),
                    outputConnected = true,
                    error = null
                )
            }
            refreshDevices()
        }
    }

    fun disconnectInput() {
        runCatching { inputReceiver?.let { inputPort?.disconnect(it) } }
        runCatching { inputPort?.close() }
        runCatching { inputDevice?.close() }
        inputInfo = null
        inputDevice = null
        inputPort = null
        inputReceiver = null
        inputUsesUmp = false
        parser.reset()
        _state.update { it.copy(inputConnected = false, inputDeviceId = null, inputDeviceName = "") }
    }

    fun disconnectOutput() {
        runCatching { outputPort?.close() }
        runCatching { outputDevice?.close() }
        outputInfo = null
        outputDevice = null
        outputPort = null
        outputUsesUmp = false
        _state.update { it.copy(outputConnected = false, outputDeviceId = null, outputDeviceName = "") }
    }

    fun setMidiInEnabled(enabled: Boolean) {
        prefs.edit().putBoolean(KEY_IN_ENABLED, enabled).apply()
        _state.update { it.copy(midiInEnabled = enabled) }
        if (!enabled) {
            prefs.edit().putBoolean(KEY_CLOCK_RECEIVE, false).apply()
            engine.setClockReceive(false)
            _state.update { it.copy(clockReceive = false) }
        }
    }

    fun setMidiOutEnabled(enabled: Boolean) {
        prefs.edit().putBoolean(KEY_OUT_ENABLED, enabled).apply()
        engine.setMidiOutEnabled(enabled)
        _state.update { it.copy(midiOutEnabled = enabled) }
    }

    fun setClockSend(enabled: Boolean) {
        prefs.edit().putBoolean(KEY_CLOCK_SEND, enabled).apply()
        engine.setClockSend(enabled)
        _state.update { it.copy(clockSend = enabled) }
    }

    fun setClockReceive(enabled: Boolean) {
        prefs.edit().putBoolean(KEY_CLOCK_RECEIVE, enabled).apply()
        engine.setClockReceive(enabled)
        _state.update { it.copy(clockReceive = enabled) }
    }

    fun setTransportSend(enabled: Boolean) {
        prefs.edit().putBoolean(KEY_TRANSPORT_SEND, enabled).apply()
        engine.setTransportSend(enabled)
        _state.update { it.copy(transportSend = enabled) }
    }

    fun setChannelFilter(channel: Int) {
        val safe = if (channel < 0) -1 else channel.coerceIn(0, 15)
        prefs.edit().putInt(KEY_CHANNEL, safe).apply()
        engine.setMidiChannel(safe)
        _state.update { it.copy(channelFilter = safe) }
    }

    fun setUseUmp(enabled: Boolean) {
        if (enabled && Build.VERSION.SDK_INT < 33) return
        prefs.edit().putBoolean(KEY_USE_UMP, enabled).apply()
        inputUsesUmp = enabled && inputInfo?.let { isUmpDevice(it) } == true
        outputUsesUmp = enabled && outputInfo?.let { isUmpDevice(it) } == true
        parser.reset()
        _state.update { it.copy(useUmp = enabled) }
    }

    fun clearLog() {
        _state.update { it.copy(log = emptyList()) }
    }

    private fun startOutputPump() {
        outputPump?.cancel()
        outputPump = scope.launch {
            while (isActive) {
                val records = engine.pollMidiOut(96)
                if (records.isNotEmpty()) {
                    val port = outputPort
                    if (port != null && _state.value.midiOutEnabled) {
                        val now = System.nanoTime()
                        for (record in records) {
                            val bytes = if (outputUsesUmp) {
                                UmpCodec.encode(record.status, record.data1, record.data2)
                            } else {
                                UmpCodec.encodeMidi1(record.status, record.data1, record.data2)
                            }
                            val timestamp = if (record.timestampNanos in now..(now + 2_000_000_000L)) {
                                record.timestampNanos
                            } else {
                                0L
                            }
                            runCatching { port.send(bytes, 0, bytes.size, timestamp) }
                            log(record.status, record.data1, record.data2, MidiDirection.OUT)
                        }
                    }
                }
                delay(2)
            }
        }
    }

    private fun handleIncoming(msg: ByteArray, offset: Int, count: Int, timestamp: Long) {
        if (!_state.value.midiInEnabled) return
        if (inputUsesUmp) {
            for (message in UmpCodec.decode(msg, offset, count)) {
                deliver(message.status, message.data1, message.data2, timestamp)
            }
        } else {
            val end = (offset + count).coerceAtMost(msg.size)
            for (i in offset until end) {
                parser.feed(msg[i].toInt(), timestamp) { status, d1, d2, ts ->
                    deliver(status, d1, d2, ts)
                }
            }
        }
    }

    private fun deliver(status: Int, data1: Int, data2: Int, timestampNanos: Long) {
        engine.pushMidi(status, data1, data2, timestampNanos)
        log(status, data1, data2, MidiDirection.IN)
    }

    private fun log(status: Int, data1: Int, data2: Int, direction: MidiDirection) {
        val now = System.currentTimeMillis()
        if (status == 0xF8) {
            val previous = lastClockLogMs.get()
            if (now - previous < 1000) return
            if (!lastClockLogMs.compareAndSet(previous, now)) return
        }
        val bytes = when {
            status >= 0xF0 && data1 == 0 && data2 == 0 -> "%02X".format(status)
            status >= 0xF0 -> "%02X %02X %02X".format(status, data1, data2)
            else -> "%02X %02X %02X".format(status, data1, data2)
        }
        val entry = MidiLogEntry(
            id = logId.incrementAndGet(),
            direction = direction,
            bytes = bytes,
            description = describe(status, data1, data2),
            timestampMs = now
        )
        _state.update {
            it.copy(
                log = (it.log + entry).takeLast(60),
                lastRxMs = if (direction == MidiDirection.IN) now else it.lastRxMs
            )
        }
    }

    private fun describe(status: Int, data1: Int, data2: Int): String {
        if (status >= 0xF0) {
            return when (status) {
                0xF8 -> "CLOCK"
                0xFA -> "START"
                0xFB -> "CONTINUE"
                0xFC -> "STOP"
                0xF2 -> "SONG POSITION ${data1 + (data2 shl 7)}"
                0xFE -> "ACTIVE SENSE"
                else -> "SYSTEM 0x%02X".format(status)
            }
        }
        val channel = (status and 0x0F) + 1
        return when (status and 0xF0) {
            0x90 -> if (data2 == 0) "CH$channel NOTE OFF ${noteName(data1)}"
            else "CH$channel NOTE ON ${noteName(data1)} VEL $data2"
            0x80 -> "CH$channel NOTE OFF ${noteName(data1)}"
            0xB0 -> "CH$channel CC ${data1} = $data2"
            0xC0 -> "CH$channel PROGRAM ${data1 + 1}"
            0xD0 -> "CH$channel PRESSURE $data1"
            0xE0 -> "CH$channel PITCH BEND ${data1 + (data2 shl 7)}"
            else -> "CH$channel 0x%02X".format(status)
        }
    }

    private fun noteName(note: Int): String {
        val names = arrayOf("C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B")
        return "${names[note.mod(12)]}${note / 12 - 1}"
    }

    private fun isUmpDevice(info: MidiDeviceInfo): Boolean {
        if (Build.VERSION.SDK_INT < 33) return false
        return runCatching {
            info.defaultProtocol != MidiDeviceInfo.PROTOCOL_UNKNOWN
        }.getOrDefault(false)
    }

    private fun deviceName(info: MidiDeviceInfo): String {
        return info.properties.getString(MidiDeviceInfo.PROPERTY_NAME)
            ?: info.properties.getString(MidiDeviceInfo.PROPERTY_PRODUCT)
            ?: "MIDI device ${info.id}"
    }

    private fun findDeviceInfo(deviceId: Int): MidiDeviceInfo? {
        val manager = midiManager ?: return null
        runCatching {
            if (Build.VERSION.SDK_INT >= 33) {
                manager.getDevicesForTransport(MidiManager.TRANSPORT_MIDI_BYTE_STREAM)
                    .firstOrNull { it.id == deviceId }
            } else {
                manager.devices?.firstOrNull { it.id == deviceId }
            }
        }.getOrNull()?.let { return it }
        if (Build.VERSION.SDK_INT >= 33) {
            runCatching {
                manager.getDevicesForTransport(MidiManager.TRANSPORT_UNIVERSAL_MIDI_PACKETS)
                    .firstOrNull { it.id == deviceId }
            }.getOrNull()?.let { return it }
        }
        return null
    }

    @Suppress("DEPRECATION")
    private fun requestUsbPermission(info: MidiDeviceInfo) {
        val manager = usbManager ?: return
        val usbDevice = info.properties.getParcelable(MidiDeviceInfo.PROPERTY_USB_DEVICE) as? UsbDevice ?: return
        if (manager.hasPermission(usbDevice)) return
        val flags = PendingIntent.FLAG_UPDATE_CURRENT or
            if (Build.VERSION.SDK_INT >= 23) PendingIntent.FLAG_IMMUTABLE else 0
        val intent = Intent(ACTION_USB_PERMISSION).setPackage(context.packageName)
        val pending = PendingIntent.getBroadcast(context, 0, intent, flags)
        runCatching { manager.requestPermission(usbDevice, pending) }
    }

    companion object {
        private const val ACTION_USB_PERMISSION = "com.danimanx.replicant303.USB_PERMISSION"
        private const val KEY_IN_ENABLED = "in_enabled"
        private const val KEY_OUT_ENABLED = "out_enabled"
        private const val KEY_CLOCK_SEND = "clock_send"
        private const val KEY_CLOCK_RECEIVE = "clock_receive"
        private const val KEY_TRANSPORT_SEND = "transport_send"
        private const val KEY_CHANNEL = "channel_filter"
        private const val KEY_USE_UMP = "use_ump"
        private const val KEY_INPUT_ID = "input_id"
        private const val KEY_OUTPUT_ID = "output_id"
        private const val KEY_INPUT_NAME = "input_name"
        private const val KEY_OUTPUT_NAME = "output_name"
    }
}
